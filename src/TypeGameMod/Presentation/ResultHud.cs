        static int TextWidth(string text, int scale)
        {
            int width = 0;
            foreach (char ch in text)
                width += (ch == ' ' ? 8 : Glyphs[ch][0].Length + 1) * scale;
            return width - scale;
        }

        static void DrawText(Dictionary<int, uint> pixels, string text, int y, int scale, bool accent)
        {
            var ink = new Dictionary<int, uint>();
            int x = (800 - TextWidth(text, scale)) / 2;
            foreach (char ch in text)
            {
                if (ch == ' ')
                {
                    x += 8 * scale;
                    continue;
                }
                string[] glyph = Glyphs[ch];
                for (int row = 0; row < glyph.Length; row++)
                    for (int col = 0; col < glyph[row].Length; col++)
                        if (glyph[row][col] == '1')
                            for (int dy = 0; dy < scale; dy++)
                                for (int dx = 0; dx < scale; dx++)
                                    ink[((y + row * scale + dy) << 10) | (x + col * scale + dx)] =
                                        accent ? (row < 7 ? Cream : Gold) : 0x00b9ccd6u;
                x += (glyph[0].Length + 1) * scale;
            }
            foreach (int key in ink.Keys)
                for (int dy = -scale; dy <= scale + 1; dy++)
                    for (int dx = -scale; dx <= scale + 1; dx++)
                        pixels[key + dy * 1024 + dx] = Outline;
            foreach (var pixel in ink)
                pixels[pixel.Key] = pixel.Value;
        }

        static void WriteSpans(byte[] bank, int offset, Dictionary<int, uint> pixels)
        {
            var spans = new List<int[]>();
            var previous = new Dictionary<long, int>();
            for (int y = 534; y < 599; y++)
            {
                var nextRow = new Dictionary<long, int>();
                for (int x = 160; x < 640;)
                {
                    uint colour;
                    if (!pixels.TryGetValue((y << 10) | x, out colour))
                    {
                        x++;
                        continue;
                    }
                    int end = x + 1;
                    uint next;
                    while (end < 640 && pixels.TryGetValue((y << 10) | end, out next) && next == colour)
                        end++;
                    long key = ((long)colour << 20) | ((long)x << 10) | (uint)end;
                    int index;
                    if (previous.TryGetValue(key, out index))
                        spans[index][3] = y + 1;
                    else
                    {
                        index = spans.Count;
                        spans.Add(new[] { x, y, end, y + 1, unchecked((int)colour) });
                    }
                    nextRow.Add(key, index);
                    x = end;
                }
                previous = nextRow;
            }
            if (4 + spans.Count * 20 > StateBytes)
                throw new InvalidOperationException("Result HUD spans exceed bank");
            BinaryFields.Write(bank, offset, (uint)spans.Count);
            offset += 4;
            foreach (int[] span in spans)
                foreach (int value in span)
                {
                    BinaryFields.Write(bank, offset, unchecked((uint)value));
                    offset += 4;
                }
        }

        internal static byte[] Build()
        {
            var bank = new byte[2 * StateBytes];
            for (int online = 0; online < 2; online++)
            {
                var pixels = new Dictionary<int, uint>();
                DrawText(pixels, "Esc 返回 / 回车再来一局", 536, 2, true);
                if (online == 1)
                    DrawText(pixels, "双方准备后开始", 578, 1, false);
                WriteSpans(bank, online * StateBytes, pixels);
            }
            return bank;
        }
