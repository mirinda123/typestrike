"""Assemble the mod's own x86 bridge and generate its C# layout constants.

Normal C# builds use the checked-in outputs and need no Python packages.
Use --check in development/CI, or --write after an intentional assembly change.
"""
import argparse
import json
import re
import struct
from pathlib import Path

from capstone import Cs, CS_ARCH_X86, CS_MODE_32, CS_GRP_CALL, CS_GRP_JUMP
from capstone.x86 import X86_OP_IMM, X86_OP_MEM
from keystone import Ks, KS_ARCH_X86, KS_MODE_32

ROOT = Path(__file__).resolve().parent.parent
NATIVE = ROOT / "native"
CAVE_BASE = 0x30000000
GAME_BASE = 0x400000
CAVE_BYTES = 0x10000


def resolve_symbol(match, layout):
    name = match.group(1)
    if name.startswith("Cave+0x"):
        return str(CAVE_BASE + int(name[5:], 16))
    group, field = name.split(".")
    if group == "Render":
        return str(CAVE_BASE + layout["CaveLayout"]["RenderCache"] + layout["SnapshotLayout"][field])
    offset = layout[group][field]
    if group == "Control":
        return str(CAVE_BASE + layout["CaveLayout"]["Control"] + offset)
    return str((GAME_BASE if group == "GameLayout" else CAVE_BASE) + offset)


def assemble(layout, blocks):
    assembler = Ks(KS_ARCH_X86, KS_MODE_32)
    decoder = Cs(CS_ARCH_X86, CS_MODE_32)
    decoder.detail = True
    payload = bytearray(CAVE_BYTES)
    relocations = []
    sizes = {}
    for block in blocks:
        text = (NATIVE / block["source"]).read_text(encoding="utf-8")
        text = "\n".join(line.split(";", 1)[0] for line in text.splitlines())
        text = re.sub(r"\$\{([^}]+)\}", lambda m: resolve_symbol(m, layout), text)
        offset = block["offset"]
        code = bytes(assembler.asm(text, CAVE_BASE + offset)[0])
        if offset + len(code) > block["limit"]:
            raise ValueError("Native block exceeds reserved space: " + block["name"])
        payload[offset:offset + len(code)] = code
        sizes[block["name"]] = len(code)
        decoded = 0
        for instruction in decoder.disasm(code, CAVE_BASE + offset):
            decoded += instruction.size
            branch = instruction.group(CS_GRP_CALL) or instruction.group(CS_GRP_JUMP)
            for operand in instruction.operands:
                if operand.type == X86_OP_IMM:
                    target, width, position = operand.imm, instruction.imm_size, instruction.imm_offset
                elif operand.type == X86_OP_MEM:
                    target, width, position = operand.mem.disp, instruction.disp_size, instruction.disp_offset
                else:
                    continue
                at = instruction.address - CAVE_BASE + position
                if CAVE_BASE <= target < CAVE_BASE + CAVE_BYTES:
                    if operand.type == X86_OP_IMM and branch:
                        continue  # Internal relative branches require no relocation.
                    if width != 4:
                        raise ValueError("Cave address is not a 32-bit field")
                    relocations.append((at, 0, target - CAVE_BASE))
                elif GAME_BASE <= target < GAME_BASE + 0x52000:
                    if width != 4:
                        raise ValueError("Game address is not a 32-bit field")
                    kind = 1 if operand.type == X86_OP_IMM and branch else 2
                    relocations.append((at, kind, target - GAME_BASE))
        if decoded != len(code):
            raise ValueError("Undecodable native bytes: " + block["name"])
    return bytes(payload), b"".join(struct.pack("<III", *entry) for entry in relocations), sizes


def layout_source(layout):
    lines = ["// <auto-generated />", "// Source: native/layout.json. Run tools/build_native.py --write.",
             "namespace TypeGameMod", "{"]
    for group, fields in layout.items():
        lines += ["    internal static class " + group, "    {"]
        kind = "int" if group in ("Control", "SnapshotLayout") else "uint"
        for name, offset in fields.items():
            literal = str(offset) if kind == "int" else "0x%xu" % offset
            lines.append("        internal const %s %s = %s;" % (kind, name, literal))
        lines += ["    }", ""]
    return "\n".join(lines).rstrip() + "\n}\n"


def main():
    arguments = argparse.ArgumentParser(description=__doc__)
    mode = arguments.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = arguments.parse_args()
    layout = json.loads((NATIVE / "layout.json").read_text(encoding="utf-8"))
    blocks = json.loads((NATIVE / "blocks.json").read_text(encoding="utf-8"))
    code, relocations, sizes = assemble(layout, blocks)
    outputs = {
        NATIVE / "generated/payload.bin": code,
        NATIVE / "generated/relocations.bin": relocations,
        ROOT / "src/TypeGameMod/Interop/MemoryLayout.g.cs": layout_source(layout).encode("utf-8"),
    }
    for path, contents in outputs.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        elif path.read_bytes() != contents:
            raise SystemExit("Generated output is stale: " + str(path.relative_to(ROOT)))
    print("PASS: %d native blocks, %d relocations, %d bytes (%s)" %
          (len(sizes), len(relocations) // 12, len(code), "written" if args.write else "verified"))


if __name__ == "__main__":
    main()
